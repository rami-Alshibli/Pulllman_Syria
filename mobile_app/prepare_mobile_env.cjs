const os = require('os');
const fs = require('fs');
const path = require('path');

function getLocalIpAddress() {
  const nets = os.networkInterfaces();
  const candidates = [];

  for (const name of Object.keys(nets)) {
    const lowerName = name.toLowerCase();
    // Skip virtual/VPN adapters
    if (
      lowerName.includes('vmware') ||
      lowerName.includes('virtual') ||
      lowerName.includes('vpn') ||
      lowerName.includes('loopback') ||
      lowerName.includes('vethernet')
    ) {
      continue;
    }

    for (const net of nets[name]) {
      const familyV4Value = typeof net.family === 'string' ? 'IPv4' : 4;
      if (net.family === familyV4Value && !net.internal) {
        if (!net.address.startsWith('169.254.')) {
          // Prioritize Wi-Fi adapter
          const isWifi = lowerName.includes('wi-fi') || lowerName.includes('wlan') || lowerName.includes('wireless');
          candidates.push({ ip: net.address, isWifi, adapter: name });
        }
      }
    }
  }

  // Best candidate is Wi-Fi, then anything else
  const wifiCandidate = candidates.find(c => c.isWifi);
  if (wifiCandidate) return wifiCandidate;
  if (candidates.length > 0) return candidates[0];

  return { ip: '127.0.0.1', isWifi: false, adapter: 'localhost' };
}

const chosen = getLocalIpAddress();
console.log(`[GoBus Mobile] Detected Network Adapter: ${chosen.adapter}`);
console.log(`[GoBus Mobile] Configured IP: ${chosen.ip}`);

const envPath = path.join(__dirname, '.env');
const envContent = `# Auto-generated by GoBus setup
EXPO_PUBLIC_API_URL=http://${chosen.ip}:3000
`;

fs.writeFileSync(envPath, envContent, 'utf8');
console.log(`[GoBus Mobile] Updated .env successfully: EXPO_PUBLIC_API_URL=http://${chosen.ip}:3000`);
